import {readFile} from 'node:fs/promises';
import {readRelease,renderRelease} from './release.mjs';
const release=await readRelease();
const source=await readFile(new URL('../src/index.html',import.meta.url),'utf8');
if(source.split('{{RELEASE_LINKS}}').length!==2)throw Error('Expected one release section');
const html=source.replace('{{RELEASE_LINKS}}',renderRelease(release));
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
if(new Set(ids).size!==ids.length)throw Error('Duplicate HTML ids');
for(const [,target]of html.matchAll(/href="#([^"]+)"/g))if(!ids.includes(target))throw Error(`Broken anchor: ${target}`);
if(!html.includes('lang="zh-CN"')||!html.includes('name="viewport"'))throw Error('Missing locale or viewport');
const allowed=new Set(['https://beian.miit.gov.cn/',release.url,`https://github.com/${release.repository}/releases`,...release.assets.map(a=>a.url)]);
for(const [,url]of html.matchAll(/(?:href|src)="((?:https?:)?\/\/[^\"]+)"/g))if(!allowed.has(url))throw Error(`Unreviewed external URL: ${url}`);
if(/<(?:script|img)[^>]+src="https?:/.test(html)||/<link[^>]+href="https?:/.test(html))throw Error('External runtime dependency');
if(!html.includes('Alpha')||!html.includes('开发版本 / 内置测试场景'))throw Error('Missing release/screenshot disclosure');
if(release.private&&!html.includes('普通访客目前暂无公共下载'))throw Error('Missing private release disclosure');
console.log(`HTML checks passed: ${ids.length} unique ids; all internal links resolve; no external runtime dependencies.`);
